export const DICTS: Record<Lang, Dict> = { en, ru };

export const SUIT_NAMES: Record<Lang, string[]> = {
  en: ["Spades", "Clubs", "Diamonds", "Hearts"],
  ru: ["пик", "треф", "бубен", "червей"],
};

export type TFn = (key: string, params?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  const d = DICTS[lang];
  return (key, params) => {
    let s = d[key] ?? en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

interface I18n {
  lang: Lang;
  t: TFn;
}
const Ctx = createContext<I18n>({ lang: "en", t: makeT("en") });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <Ctx.Provider value={{ lang, t: makeT(lang) }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

/** Render a translated string that contains simple <b>/<kbd> markup plus React nodes for {params}. */
export function Rich({ text, nodes = {} }: { text: string; nodes?: Record<string, ReactNode> }) {
  const parts: ReactNode[] = [];
  const re = /<(b|kbd)>(.*?)<\/\1>|\{(\w+)\}/g;
  let last = 0;
  let m: RegExpExecArray | null;
  let i = 0;
  while ((m = re.exec(text))) {
    if (m.index > last) parts.push(text.slice(last, m.index));
    if (m[1] === "b") parts.push(<b key={i++}>{m[2]}</b>);
    else if (m[1] === "kbd") parts.push(<kbd key={i++}>{m[2]}</kbd>);
    else parts.push(<span key={i++}>{nodes[m[3]] ?? `{${m[3]}}`}</span>);
    last = m.index + m[0].length;
  }
  if (last < text.length) parts.push(text.slice(last));
  return <>{parts}</>;
}
